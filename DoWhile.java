//Working with Do..While in Java
public class DoWhile {
public static void main(String[]args) {
	
	int x=10;             //Declare Variable x
	do {
		System.out.print("The value of X is:"+x);
		x++;              //incremental
		System.out.print("\n");  //print outputs on a new line
	}while(x<=20);
}
}
