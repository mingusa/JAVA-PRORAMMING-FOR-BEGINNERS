//Demonstrating Switch Statement
public class SwitchStatementDemo {
public static void main(String[]args) {
	int month=6;
	String monthlystring=null;
	switch(month) {
	 case 1:monthlystring="Jan";
	       break;
	 case 2:monthlystring="Feb";
	       break;
	 case 3:monthlystring="March";
	        break;
	 case 4:monthlystring="April";
	        break;
	 case 5:monthlystring="May";
	        break;
	 case 6:monthlystring="Jun";
	        break;
	 case 7:monthlystring="July";
	        break;
	 case 8:monthlystring="August";
	        break;
	
	}
	System.out.print(monthlystring);	
}
}
